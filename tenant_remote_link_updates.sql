-- Run this on the PS Time online-system database after taking a backup.
-- It is idempotent: only legacy tenants whose external_subscription_id is still NULL are updated.

START TRANSACTION;

UPDATE tenants
SET external_subscription_id = CASE id
    WHEN '01M1CDESHCPMTD2YZ8FDHBGAW4' THEN 'online-instance:4'
    WHEN '01M267SSF4HVXVTNA7XEYKC400' THEN 'online-instance:5'
    WHEN '01M2JCJ9YGC6FE6ZZ7P2J8J1YH' THEN 'online-instance:6'
    WHEN '01M2JCM0384PH404XFD3DDSF4P' THEN 'online-instance:7'
    WHEN '01M2JZXTCZ64C9ZMW1ZSR8E9SH' THEN 'online-instance:8'
    WHEN '01M2V9V7MCD5TYZFD672XCRTES' THEN 'online-instance:9'
    WHEN '01M2WAK4D4QS6VCR4RVB96TKT4' THEN 'online-instance:10'
    WHEN '01M2XD7GBR8Y4T5GFH22GJVPFF' THEN 'online-instance:11'
    WHEN '01M3CN7GDPKGZRBMGCFTXARP8Z' THEN 'online-instance:12'
    WHEN '01M3CXSJ5HC7ZR0HT2B4FZH4YP' THEN 'online-instance:13'
END,
updated_at = CURRENT_TIMESTAMP
WHERE id IN (
    '01M1CDESHCPMTD2YZ8FDHBGAW4',
    '01M267SSF4HVXVTNA7XEYKC400',
    '01M2JCJ9YGC6FE6ZZ7P2J8J1YH',
    '01M2JCM0384PH404XFD3DDSF4P',
    '01M2JZXTCZ64C9ZMW1ZSR8E9SH',
    '01M2V9V7MCD5TYZFD672XCRTES',
    '01M2WAK4D4QS6VCR4RVB96TKT4',
    '01M2XD7GBR8Y4T5GFH22GJVPFF',
    '01M3CN7GDPKGZRBMGCFTXARP8Z',
    '01M3CXSJ5HC7ZR0HT2B4FZH4YP'
)
AND external_subscription_id IS NULL;

SELECT id, external_subscription_id, provisioning_request_id
FROM tenants
WHERE id IN (
    '01M1CDESHCPMTD2YZ8FDHBGAW4',
    '01M267SSF4HVXVTNA7XEYKC400',
    '01M2JCJ9YGC6FE6ZZ7P2J8J1YH',
